import { CEFRLevel, VocabItem } from '@/types/curriculum';

export interface ThematicVocabPack {
  id: string;
  level: CEFRLevel;
  titlePl: string;
  titleRu: string;
  descriptionRu: string;
  iconEmoji: string;
  words: VocabItem[];
}

interface RawPackEntry {
  id: string;
  pl: string;
  ru: string;
  pron: string;
  pos: 'noun' | 'verb' | 'adj' | 'adv' | 'phrase';
  gender?: 'm' | 'f' | 'n';
  exPl: string;
  exRu: string;
  srsPrompt: string;
  srsAns: string[];
  falseFriend?: string;
  govHint?: string;
}

function buildVocabItems(entries: RawPackEntry[]): VocabItem[] {
  return entries.map((e) => ({
    id: e.id,
    pl: e.pl,
    ru: e.ru,
    pronunciationHint: e.pron,
    audioUrl: `/audio/vocab-packs/${e.id}.mp3`,
    partOfSpeech: e.pos,
    gender: e.gender,
    falseFriendWarning: e.falseFriend,
    governmentHint: e.govHint,
    examples: [{ pl: e.exPl, ru: e.exRu }],
    srsPromptSentence: e.srsPrompt,
    srsAcceptedAnswers: e.srsAns,
    srsBaseHint: e.ru,
  }));
}

